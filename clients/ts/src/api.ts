/**
 * @agentpay/client — thin client for the hosted AgentPay integration API (`/api/v1`).
 *
 * This is NOT the on-chain client. `OnChainBudget` / `WalletdClient` (this package's other exports)
 * talk directly to a Tari wallet daemon and are for the OWNER/operator who runs the hosted service.
 * A third-party developer or an autonomous agent should NOT touch walletd — they call the owner's
 * hosted HTTP API with an API key, and the on-chain AgentBudget enforces the spending limits. This
 * class is a tiny, dependency-free wrapper over `fetch` for exactly that: get a key → make a capped
 * payment → poll the receipt → recover from a failure via the idempotency key.
 *
 * Node 18+ (global fetch) or any modern browser. Zero runtime dependencies.
 */

export type ApiRole = "agent" | "admin";

export interface Receipt {
  id: string;
  status: "pending" | "confirmed" | "rejected" | "unknown";
  txId: string | null;
  amount: string | null;
  merchant: string | null;
  merchantName: string | null;
  memo: string | null;
  invoiceId: string | null;
  reason: string | null;
  createdAt: string | null;
  updatedAt: string | null;
}

export interface Merchant {
  address: string;
  name: string | null;
}

export interface Budget {
  component: string;
  perTxCap: string;
  dailyCap: string;
  spent: string;
  dailyRemaining: string;
  treasury: string;
  balance: string;
  revoked: boolean;
  frozen: boolean;
  window: unknown;
  whitelist: Merchant[];
  funded: string;
  withdrawn: string;
  source: Record<string, unknown>;
}

/** An error from the API carrying the HTTP status and any policy flags (frozen / rateLimited). */
export class AgentPayApiError extends Error {
  status: number;
  frozen: boolean;
  rateLimited: boolean;
  body: any;
  constructor(status: number, message: string, body?: any) {
    super(message);
    this.name = "AgentPayApiError";
    this.status = status;
    this.body = body;
    this.frozen = Boolean(body && body.frozen);
    this.rateLimited = Boolean(body && body.rateLimited);
  }
}

export interface AgentPayApiOptions {
  /** Base URL of the hosted dashboard, e.g. "https://pay.example.com" (no trailing /api/v1). */
  baseUrl: string;
  /** The bearer API key issued by the owner (agent or admin). */
  apiKey: string;
  /** Override the fetch implementation (tests, custom agents). Defaults to global fetch. */
  fetch?: typeof fetch;
}

export interface PayParams {
  merchant: string; // friendly name or component_… address
  amount: string | number | bigint; // base-unit integer
  memo?: string;
  invoiceId?: string; // ^[a-z0-9]{8,32}$ ; auto-generated by the server if omitted
  agentTag?: string;
  /** Idempotency key — a repeat with the same key never double-spends and returns the first receipt.
   *  Strongly recommended; defaults to a random key per call if omitted. */
  idempotencyKey?: string;
}

/** 16 lowercase hex chars — a safe default idempotency key / invoice id. */
function randomId(): string {
  const bytes = new Uint8Array(8);
  const g = globalThis as any;
  if (g.crypto && typeof g.crypto.getRandomValues === "function") g.crypto.getRandomValues(bytes);
  if (!bytes.some((b) => b)) for (let i = 0; i < 8; i++) bytes[i] = Math.floor(Math.random() * 256);
  return Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
}

export class AgentPayApiClient {
  private base: string;
  private apiKey: string;
  private _fetch: typeof fetch;

  constructor(opts: AgentPayApiOptions) {
    if (!opts || !opts.baseUrl) throw new Error("AgentPayApiClient: baseUrl is required");
    if (!opts.apiKey) throw new Error("AgentPayApiClient: apiKey is required");
    this.base = opts.baseUrl.replace(/\/+$/, "");
    this.apiKey = opts.apiKey;
    this._fetch = opts.fetch || (globalThis.fetch as typeof fetch);
    if (!this._fetch) throw new Error("AgentPayApiClient: no fetch available (Node 18+ or pass opts.fetch)");
  }

  private async request<T>(method: string, path: string, body?: any, headers: Record<string, string> = {}): Promise<T> {
    const res = await this._fetch(`${this.base}/api/v1${path}`, {
      method,
      headers: {
        Authorization: `Bearer ${this.apiKey}`,
        ...(body !== undefined ? { "Content-Type": "application/json" } : {}),
        ...headers,
      },
      body: body !== undefined ? JSON.stringify(body) : undefined,
    });
    const text = await res.text();
    let data: any = undefined;
    try {
      data = text ? JSON.parse(text) : undefined;
    } catch {
      data = { error: text };
    }
    if (!res.ok) {
      throw new AgentPayApiError(res.status, (data && data.error) || `HTTP ${res.status}`, data);
    }
    return data as T;
  }

  /**
   * Make a capped payment. Returns the receipt even when the chain REJECTS it (receipt.status
   * === "rejected" with a reason) — a 402 is a verdict, not a transport error. Transport/validation
   * failures throw AgentPayApiError. Pass `idempotencyKey` (or let it default) so a retry after a
   * network blip is safe: the same key returns the original receipt instead of paying twice.
   */
  async pay(params: PayParams): Promise<{ receipt: Receipt; replayed: boolean }> {
    const idem = params.idempotencyKey || `pay_${randomId()}`;
    const body: any = { merchant: params.merchant, amount: String(params.amount) };
    if (params.memo !== undefined) body.memo = params.memo;
    if (params.invoiceId !== undefined) body.invoiceId = params.invoiceId;
    if (params.agentTag !== undefined) body.agentTag = params.agentTag;
    try {
      return await this.request("POST", "/payments", body, { "Idempotency-Key": idem });
    } catch (e) {
      // A 402 (chain rejection) carries a receipt in its body — surface it as a receipt, not a throw.
      if (e instanceof AgentPayApiError && e.status === 402 && e.body && e.body.receipt) {
        return { receipt: e.body.receipt as Receipt, replayed: Boolean(e.body.replayed) };
      }
      throw e;
    }
  }

  /** Fetch one receipt by payment id (the idempotency key). The server settles it against chain. */
  async getPayment(id: string): Promise<Receipt> {
    const r = await this.request<{ receipt: Receipt }>("GET", `/payments/${encodeURIComponent(id)}`);
    return r.receipt;
  }

  /** List all payment receipts. */
  async listPayments(): Promise<Receipt[]> {
    const r = await this.request<{ payments: Receipt[] }>("GET", "/payments");
    return r.payments;
  }

  /**
   * Poll a payment until it reaches a terminal status (confirmed/rejected) or the attempts run out.
   * Returns the last receipt seen (which may still be pending/unknown — inspect `.status`).
   */
  async waitForPayment(id: string, opts: { tries?: number; delayMs?: number } = {}): Promise<Receipt> {
    const tries = opts.tries ?? 20;
    const delayMs = opts.delayMs ?? 1500;
    let last = await this.getPayment(id);
    for (let i = 0; i < tries && (last.status === "pending" || last.status === "unknown"); i++) {
      await new Promise((r) => setTimeout(r, delayMs));
      last = await this.getPayment(id);
    }
    return last;
  }

  /** Budget status (caps, remaining this window, treasury) — all chain-derived. */
  async getBudget(): Promise<Budget> {
    const r = await this.request<{ budget: Budget }>("GET", "/budget");
    return r.budget;
  }

  /** The on-chain merchant whitelist. */
  async listMerchants(): Promise<Merchant[]> {
    const r = await this.request<{ merchants: Merchant[] }>("GET", "/merchants");
    return r.merchants;
  }

  // ---- admin-key operations (throw 403 with an agent key) --------------------------------------

  /** Open/fund a budget (admin key). */
  async openBudget(params: {
    fund: string | number | bigint;
    perTxCap: string | number | bigint;
    dailyCap: string | number | bigint;
    epochsPerWindow?: number;
    whitelist?: string[];
  }): Promise<Budget> {
    const r = await this.request<{ budget: Budget }>("POST", "/budgets", {
      fund: String(params.fund),
      perTxCap: String(params.perTxCap),
      dailyCap: String(params.dailyCap),
      epochsPerWindow: params.epochsPerWindow,
      whitelist: params.whitelist || [],
    });
    return r.budget;
  }

  /** Add a merchant to the whitelist (admin key). Returns the updated whitelist. */
  async addMerchant(merchant: string): Promise<Merchant[]> {
    const r = await this.request<{ merchants: Merchant[] }>("POST", "/merchants", { merchant });
    return r.merchants;
  }

  /** Remove a local merchant alias (admin key). See docs/api.md for the on-chain caveat. */
  async removeMerchantAlias(name: string): Promise<{ removedAlias: boolean; notice: string }> {
    return await this.request("DELETE", `/merchants/${encodeURIComponent(name)}`);
  }

  /** Recent audit entries (admin key). */
  async getAudit(limit = 100): Promise<any[]> {
    const r = await this.request<{ entries: any[] }>("GET", `/audit?limit=${encodeURIComponent(String(limit))}`);
    return r.entries;
  }
}
